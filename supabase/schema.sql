create table if not exists public."Snippet" (
  id bigint generated by default as identity primary key,
  title text not null,
  code text not null
);

alter table public."Snippet" enable row level security;

drop policy if exists "Allow public snippet reads" on public."Snippet";
create policy "Allow public snippet reads"
  on public."Snippet" for select
  to anon, authenticated
  using (true);

drop policy if exists "Allow public snippet creates" on public."Snippet";
create policy "Allow public snippet creates"
  on public."Snippet" for insert
  to anon, authenticated
  with check (true);

drop policy if exists "Allow public snippet updates" on public."Snippet";
create policy "Allow public snippet updates"
  on public."Snippet" for update
  to anon, authenticated
  using (true)
  with check (true);

drop policy if exists "Allow public snippet deletes" on public."Snippet";
create policy "Allow public snippet deletes"
  on public."Snippet" for delete
  to anon, authenticated
  using (true);

